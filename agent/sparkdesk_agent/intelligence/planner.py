"""Task Planner for SparkDesk Local Agent.

Converts classified natural language intents into structured, inspectable
execution plans. Ensures all planned steps are deterministic and map strictly
to tools before entering validation and execution.
"""

from datetime import datetime, timezone
from enum import Enum
from typing import Any, Dict, List, Optional
import uuid

from pydantic import BaseModel, Field

from sparkdesk_agent.core.logging import get_logger
from sparkdesk_agent.intelligence.context import ConversationContext
from sparkdesk_agent.intent.models import IntentResult, IntentStatus


class PlanStatus(str, Enum):
    """Lifecycle state of an execution plan."""

    DRAFT = "draft"
    VALIDATED = "validated"
    EXECUTING = "executing"
    COMPLETED = "completed"
    FAILED = "failed"
    REJECTED = "rejected"


class PlanStep(BaseModel):
    """An individual discrete tool invocation step in an execution plan."""

    step_id: int = Field(..., description="Sequential step number, starting from 1")
    tool: str = Field(..., description="Target tool identifier to invoke")
    parameters: Dict[str, Any] = Field(default_factory=dict, description="Validated arguments to pass to the tool")
    description: str = Field(default="", description="Human-readable explanation of why this step is taken")


class ExecutionPlan(BaseModel):
    """Structured execution plan generated by the Task Planner."""

    plan_id: str = Field(default_factory=lambda: str(uuid.uuid4()), description="Unique plan UUID")
    intent: Optional[str] = Field(default=None, description="Intent that prompted plan creation")
    focus: Optional[str] = Field(default="all", description="Metric focus, e.g. memory, cpu, disk, uptime")
    status: PlanStatus = Field(default=PlanStatus.DRAFT, description="Current lifecycle state of the plan")
    steps: List[PlanStep] = Field(default_factory=list, description="Ordered tool execution steps")
    rationale: str = Field(default="", description="Strategic justification for this plan")
    created_at: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
    error: Optional[str] = Field(default=None, description="Error message if plan generation or execution fails")

    def is_executable(self) -> bool:
        """Determine if this plan is valid and ready for execution."""
        return bool(self.steps and self.status in (PlanStatus.DRAFT, PlanStatus.VALIDATED))


class TaskPlanner:
    """Translates classified intents into structured, executable plans."""

    def __init__(self) -> None:
        self._logger = get_logger("sparkdesk_agent.intelligence.planner")

    def create_plan(
        self,
        intent: IntentResult,
        context: Optional[ConversationContext] = None,
    ) -> ExecutionPlan:
        """Construct an ExecutionPlan from an IntentResult and optional context."""
        plan_id = str(uuid.uuid4())

        # 1. Reject Ambiguous requests cleanly without generating executable steps
        if intent.status == IntentStatus.AMBIGUOUS:
            self._logger.info("Plan rejected: ambiguous intent")
            return ExecutionPlan(
                plan_id=plan_id,
                intent=intent.intent,
                focus=intent.focus,
                status=PlanStatus.REJECTED,
                steps=[],
                rationale=intent.message or "Ambiguous request. User clarification required before planning.",
            )

        # 2. Reject Unsupported requests cleanly
        if intent.status == IntentStatus.UNSUPPORTED:
            self._logger.info("Plan rejected: unsupported intent")
            return ExecutionPlan(
                plan_id=plan_id,
                intent=intent.intent,
                focus=intent.focus,
                status=PlanStatus.REJECTED,
                steps=[],
                rationale=intent.message or "Unsupported capability requested.",
            )

        # 3. Create plan for Recognized intent
        if intent.status == IntentStatus.RECOGNIZED:
            if not intent.tool:
                self._logger.error("Recognized intent '%s' lacks target tool", intent.intent)
                return ExecutionPlan(
                    plan_id=plan_id,
                    intent=intent.intent,
                    focus=intent.focus,
                    status=PlanStatus.FAILED,
                    steps=[],
                    rationale="Intent was marked recognized but did not specify a target tool.",
                    error="Missing target tool in recognized intent.",
                )

            step = PlanStep(
                step_id=1,
                tool=intent.tool,
                parameters=dict(intent.parameters),
                description=f"Invoke registered tool '{intent.tool}' (focus: {intent.focus or 'all'}).",
            )

            plan = ExecutionPlan(
                plan_id=plan_id,
                intent=intent.intent,
                focus=intent.focus or "all",
                status=PlanStatus.DRAFT,
                steps=[step],
                rationale=f"Execute tool '{intent.tool}' to fulfill user request for '{intent.intent}'.",
            )
            self._logger.info("Created ExecutionPlan '%s' with %d step(s)", plan_id, len(plan.steps))
            return plan

        # Fallback for unexpected status
        return ExecutionPlan(
            plan_id=plan_id,
            intent=intent.intent,
            status=PlanStatus.REJECTED,
            steps=[],
            rationale="Unrecognized intent status.",
        )


# Global task planner singleton
task_planner = TaskPlanner()

